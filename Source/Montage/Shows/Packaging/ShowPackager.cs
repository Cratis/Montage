using System.Diagnostics;
using System.IO.Compression;

namespace Montage.Shows.Packaging;

/// <summary>
/// Assembles the show package: a folder the engine serves as-is, zipped as the durable artifact.
/// <para>Package layout:</para>
///   show.json            the spec
///   audio/voiceover.mp3  the narration
///   data/lyrics.json     word timings
///   data/audio.json      envelope analysis
///   README.md            a human-readable manifest
/// </summary>
public interface IShowPackager
{
    /// <summary>
    /// Writes the package directory for a show.
    /// </summary>
    /// <param name="showId">The show.</param>
    /// <param name="title">The show title for the README.</param>
    /// <param name="specJson">The show spec JSON.</param>
    /// <param name="lyricsJson">The lyrics JSON.</param>
    /// <param name="audioAnalysisJson">The audio analysis JSON.</param>
    /// <param name="voiceoverSource">Path of the narration audio to copy (mp3 or wav).</param>
    /// <returns>The package directory path.</returns>
    string WritePackageDirectory(ShowId showId, string title, string specJson, string lyricsJson, string audioAnalysisJson, string voiceoverSource);

    /// <summary>
    /// Zips a package directory next to itself ({showFolder}/package.zip), overwriting any previous zip.
    /// </summary>
    /// <param name="packageDirectory">The package directory.</param>
    /// <param name="destinationZip">Where to write the zip.</param>
    void Zip(string packageDirectory, string destinationZip);
}

/// <summary>
/// Initializes a new instance of the <see cref="ShowPackager"/> class.
/// </summary>
/// <param name="artifactStore">The artifact store.</param>
public sealed class ShowPackager(ShowArtifactStore artifactStore) : IShowPackager
{
    /// <inheritdoc/>
    public string WritePackageDirectory(ShowId showId, string title, string specJson, string lyricsJson, string audioAnalysisJson, string voiceoverSource)
    {
        var package = artifactStore.PackageDirectory(showId);
        if (Directory.Exists(package)) Directory.Delete(package, recursive: true);
        Directory.CreateDirectory(Path.Combine(package, "audio"));
        Directory.CreateDirectory(Path.Combine(package, "data"));

        File.WriteAllText(Path.Combine(package, "show.json"), specJson);
        File.WriteAllText(Path.Combine(package, "data", "lyrics.json"), lyricsJson);
        File.WriteAllText(Path.Combine(package, "data", "audio.json"), audioAnalysisJson);

        if (File.Exists(voiceoverSource))
        {
            var extension = Path.GetExtension(voiceoverSource);
            var targetName = extension.Equals(".mp3", StringComparison.OrdinalIgnoreCase) ? "voiceover.mp3" : $"voiceover{extension}";
            File.Copy(voiceoverSource, Path.Combine(package, "audio", targetName), overwrite: true);
        }

        CopyAssets(artifactStore.AssetsFolderFor(showId), package);

        File.WriteAllText(Path.Combine(package, "README.md"), $"""
            # {title}

            A show package for [montage-engine](https://github.com/cratis). Generated by Cratis Montage.

            - `show.json` — the spec: scenes, timing, transitions, brand
            - `audio/` — the voiceover
            - `data/` — word timings and the voice envelope analysis

            Preview it with the engine, or drop it into any tooling that speaks this format.
            Every frame is a deterministic function of time.
            """);
        return package;
    }

    /// <summary>
    /// Copies the show's durable assets into the package, preserving relative paths.
    /// </summary>
    /// <param name="assets">The assets folder; missing means nothing to copy.</param>
    /// <param name="package">The package directory.</param>
    static void CopyAssets(string assets, string package)
    {
        if (!Directory.Exists(assets)) return;
        foreach (var file in Directory.EnumerateFiles(assets, "*", SearchOption.AllDirectories))
        {
            var target = Path.Combine(package, Path.GetRelativePath(assets, file));
            Directory.CreateDirectory(Path.GetDirectoryName(target)!);
            File.Copy(file, target, overwrite: true);
        }
    }

    /// <inheritdoc/>
    public void Zip(string packageDirectory, string destinationZip)
    {
        if (File.Exists(destinationZip)) File.Delete(destinationZip);
        ZipFile.CreateFromDirectory(packageDirectory, destinationZip, CompressionLevel.Optimal, includeBaseDirectory: false);
    }
}

/// <summary>
/// Thin wrapper over the ffmpeg CLI for the audio steps the pipeline needs
/// (WAV to MP3 for playback/packaging). Video encoding lives in the engine's renderer.
/// </summary>
public interface IFfmpeg
{
    /// <summary>
    /// Converts a WAV file to MP3 (192 kbps). Returns false when ffmpeg is unavailable.
    /// </summary>
    /// <param name="sourceWav">The WAV file.</param>
    /// <param name="destinationMp3">The MP3 file.</param>
    /// <returns>True when the conversion ran; false when ffmpeg is not on PATH.</returns>
    bool ConvertToMp3(string sourceWav, string destinationMp3);

    /// <summary>
    /// Gets a value indicating whether ffmpeg is available on PATH.
    /// </summary>
    bool IsAvailable { get; }
}

/// <summary>
/// Initializes a new instance of the <see cref="Ffmpeg"/> class.
/// </summary>
public sealed class Ffmpeg : IFfmpeg
{
    /// <inheritdoc/>
    public bool IsAvailable { get; } = LocateFfmpeg();

    static bool LocateFfmpeg()
    {
        try
        {
            var psi = new ProcessStartInfo("ffmpeg", ["-version"])
            {
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
            };
            using var p = Process.Start(psi);
            if (p is null) return false;
            p.WaitForExit(5000);
            return p.ExitCode == 0;
        }
        catch
        {
            return false;
        }
    }

    /// <inheritdoc/>
    public bool ConvertToMp3(string sourceWav, string destinationMp3)
    {
        if (!IsAvailable) return false;
        var psi = new ProcessStartInfo("ffmpeg", ["-y", "-loglevel", "error", "-i", sourceWav, "-codec:a", "libmp3lame", "-b:a", "192k", destinationMp3])
        {
            UseShellExecute = false,
            RedirectStandardError = true,
        };
        using var p = Process.Start(psi);
        if (p is null) return false;
        var stderr = p.StandardError.ReadToEnd();
        p.WaitForExit();
        if (p.ExitCode != 0) throw new InvalidOperationException($"ffmpeg failed: {stderr[..Math.Min(stderr.Length, 500)]}");
        return true;
    }
}
